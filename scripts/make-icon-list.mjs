/**
 * Regenerate `src/iconAliases.ts` from the `lucide-static` package.
 *
 * Obsidian's `getIconIds()` tells us which icons exist in the running app but
 * not what they're called colloquially, so the icon picker needs this table to
 * resolve searches like "wheelchair" to `lucide-accessibility`.
 *
 * Run with `npm run icons` after bumping `lucide-static`. The output is a
 * snapshot, not a source of truth: the picker works fine when it drifts, so
 * this only needs running when the aliases are worth refreshing.
 *
 * The file is emitted one icon per line and listed in `.prettierignore` --
 * formatting it expands every alias array and multiplies its length tenfold.
 */
import fs from 'fs/promises';
import { createRequire } from 'module';
import path from 'path';

const require = createRequire(import.meta.url);

const OUT = './src/iconAliases.ts';

const HEADER = `/**
 * Search aliases for Lucide icons, generated by \`npm run icons\`. Do not edit.
 *
 * Obsidian's \`getIconIds()\` reports which icons the running app actually has,
 * but not their search aliases, so this table supplies them. It is a snapshot:
 * ids it lists that the app no longer registers are ignored, and icons the app
 * has that are missing here stay searchable by id. That keeps the icon picker
 * working across Obsidian versions without needing this file to be current.
 */
export const iconAliases: Record<string, string[]> = {
`;

const tagsPath = path.join(
  path.dirname(require.resolve('lucide-static/package.json')),
  'tags.json'
);

const tags = JSON.parse(await fs.readFile(tagsPath, 'utf8'));

// Obsidian registers Lucide icons under a `lucide-` prefix.
const lines = Object.entries(tags)
  .map(([name, aliases]) => [`lucide-${name}`, aliases])
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, aliases]) => `  ${JSON.stringify(id)}: ${JSON.stringify(aliases)},`);

await fs.writeFile(OUT, `${HEADER}${lines.join('\n')}\n};\n`);

const { version } = require('lucide-static/package.json');
console.log(
  `Wrote ${lines.length} icons from lucide-static@${version} to ${OUT}`
);
